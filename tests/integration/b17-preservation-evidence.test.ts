import { env } from "cloudflare:workers";
import { applyD1Migrations } from "cloudflare:test";
import { expect, it } from "vitest";
import { createDb } from "../../app/db/client.server";
import { places } from "../../app/db/schema";
import { seedApprovedReviewerVote } from "./reviewer-public-fixtures";
import { B17_PRESERVATION_COLUMNS, B17_PRESERVATION_LIMITS, buildB17PreservationCatalogQuery, planB17PreservationCapture, collectB17PreservationSnapshot, compareB17PreservationSnapshots } from "../../scripts/b17-preservation-evidence.mjs";

it("preserves every 0049 column and rowid through nine B17 migrations and rejects incomplete evidence", async () => {
  const db = (env as unknown as { MIGRATION_DB: D1Database }).MIGRATION_DB;
  const catalog = async () => (await db.prepare(buildB17PreservationCatalogQuery().sql).all()).results;
  const capture = async (phase: "before" | "after") => {
    const plan = planB17PreservationCapture({ phase, catalog: await catalog() });
    const results: Record<string, unknown[]> = {};
    for (const query of plan.queries) results[query.id] = (await db.prepare(query.sql).all()).results;
    return { plan, results, snapshot: collectB17PreservationSnapshot(plan, results) };
  };
  await applyD1Migrations(db, env.TEST_MIGRATIONS.filter(item => item.name < "0050"));
  const originalCatalog = await catalog();
  const originalColumns: Record<string, string[]> = {};
  for (const row of originalCatalog.filter((r) => r.kind === "column").sort((a,b) => Number(a.cid) - Number(b.cid))) {
    (originalColumns[String(row.table_name)] ??= []).push(String(row.name));
  }
  expect(B17_PRESERVATION_COLUMNS).toEqual(originalColumns);
  expect(Object.isFrozen(B17_PRESERVATION_COLUMNS)).toBe(true);
  expect(Object.values(B17_PRESERVATION_COLUMNS).every(Object.isFrozen)).toBe(true);
  expect(() => planB17PreservationCapture({ phase: "before", catalog: originalCatalog.slice(1) })).toThrow("CATALOG_MISMATCH");
  expect(() => planB17PreservationCapture({ phase: "before", catalog: [...originalCatalog, { ...originalCatalog[0], name: "unsafe;name" }] })).toThrow("IDENTIFIER");
  const now = "2026-11-18T01:00:00.000Z", later = "2026-12-10T01:00:00.000Z";
  await db.prepare("INSERT INTO users(rowid,id,email,display_name,role,password_hash,password_salt,created_at,updated_at) VALUES(-91,'b17-preserve-owner','b17-preserve@example.test','보존 합성 관리자','ADMIN',CAST('synthetic bytes' AS BLOB),'',?,?)").bind(now, now).run();
  await db.prepare("INSERT INTO sessions(id,user_id,expires_at,created_at) VALUES('b17-preserve-session','b17-preserve-owner',?,?)").bind(later, now).run();
  await db.prepare("INSERT INTO admin_session_assurances(session_id,actor_user_id,method,verified_at,expires_at) VALUES('b17-preserve-session','b17-preserve-owner','EMAIL',?,?)").bind(now,later).run();
  await db.prepare("INSERT INTO admin_role_restorations(user_id,previous_role) VALUES('b17-preserve-owner','REVIEWER')").run();
  await db.prepare("UPDATE student_seats SET user_id='b17-preserve-owner',can_classify_places=1,can_approve_registration=1 WHERE code='A'").run();
  await db.prepare("INSERT INTO student_invitations(id,seat_code,token_hash,expires_at,created_by,created_at) VALUES('b17-preserve-invite','B','synthetic-hash',?,'b17-preserve-owner',?)").bind(later,now).run();
  await db.prepare("INSERT INTO student_tasks(id,kind,target_id,title,assigned_seat,checker_seat,version,classification_json,created_by,created_at,updated_at) VALUES('b17-preserve-task','QA','synthetic-target','보존 합성 작업','A','B',9007199254740993,'{}','b17-preserve-owner',?,?)").bind(now,now).run();
  await db.prepare("INSERT INTO student_task_revisions(id,task_id,version,actor_user_id,actor_seat,event_type,payload_json,created_at) VALUES('b17-preserve-revision','b17-preserve-task',1,'b17-preserve-owner','A','SUBMIT','{}',?)").bind(now).run();
  const appDb = createDb(db);
  await appDb.insert(places).values({ id: "b17-preserve-place", slug: "b17-preserve-place", name: "보존 합성 장소", status: "PUBLISHED", address: "합성 주소", neighborhood: "합성", latitude: 35.1, longitude: 126.9, searchText: "b17-preserve-place", createdAt: now, updatedAt: now });
  const { reviewId } = await seedApprovedReviewerVote(appDb, { reviewerId: "b17-preserve-owner", placeId: "b17-preserve-place", eventId: "b17-preserve-vote", value: 1, now, withPhoto: true });
  await db.prepare("INSERT INTO reviewer_photo_cleanup_jobs(review_id,purpose,object_keys_json,next_attempt_at,created_at,updated_at) VALUES(?,'DELETE','[\"synthetic/photo.jpg\"]',?,?,?)").bind(reviewId,now,now,now).run();
  await db.prepare("INSERT INTO admin_audit_logs(id,actor_user_id,action,target_type,target_id,after_state,created_at) VALUES('b17-preserve-audit','b17-preserve-owner','PRESERVATION_FIXTURE','PLACE','b17-preserve-place','{}',?)").bind(now).run();
  const before = await capture("before");
  const upgrades = env.TEST_MIGRATIONS.filter(item => item.name >= "0050");
  expect(upgrades).toHaveLength(9);
  await applyD1Migrations(db, upgrades);
  const after = await capture("after");
  const result = compareB17PreservationSnapshots(before.snapshot, after.snapshot);
  expect(result.ok).toBe(true);
  expect(result.tableCount).toBe(82);
  expect(result.mismatchCount).toBe(0);
  for (const table of ["users", "sessions", "admin_session_assurances", "admin_role_restorations", "student_seats", "student_invitations", "student_tasks", "student_task_revisions", "reviewer_profiles", "reviewer_visit_reviews", "reviewer_visit_photos", "vote_events", "current_votes", "rating_configs", "reviewer_photo_cleanup_jobs", "admin_audit_logs"]) {
    expect(before.snapshot.tables[table].rows.length, table).toBeGreaterThan(0);
  }
  const user = before.snapshot.tables.users.rows.find((row: {rowid: string}) => row.rowid === "-91")!;
  expect(user.values[before.snapshot.tables.users.columns.indexOf("password_hash")]).toEqual(["blob", "73796E746865746963206279746573"]);
  expect(user.values[before.snapshot.tables.users.columns.indexOf("password_salt")]).toEqual(["text", ""]);
  const task = before.snapshot.tables.student_tasks;
  expect(task.rows[0].values[task.columns.indexOf("version")]).toEqual(["integer", "9007199254740993"]);
  expect((await db.prepare("PRAGMA foreign_key_check").all()).results).toEqual([]);
  expect(before.plan.queries).toHaveLength(7);
  expect(after.plan.queries).toHaveLength(7);
  expect(before.plan.queries.every((q: { sql: string; sqlStatementCount: number; d1CommandCount: number }) => q.sql.length <= B17_PRESERVATION_LIMITS.maxSqlBytes && q.sqlStatementCount === 1 && q.d1CommandCount === 1)).toBe(true);

  const clone = <T,>(value: T): T => JSON.parse(JSON.stringify(value));
  const firstId = before.plan.queries[0].id;
  const missingQuery = clone(before.results); delete missingQuery[firstId];
  expect(() => collectB17PreservationSnapshot(before.plan, missingQuery)).toThrow("QUERIES");
  const missingTable = clone(before.results);
  missingTable[firstId] = missingTable[firstId].filter((r) => (r as {table_name: string}).table_name !== before.plan.queries[0].tables[0]);
  expect(() => collectB17PreservationSnapshot(before.plan, missingTable)).toThrow("OMISSION");
  const truncated = clone(before.results);
  const populatedId = before.plan.queries.find((q: {tables: string[]}) => q.tables.includes("users"))!.id;
  const userRows = truncated[populatedId] as {table_name: string; row_id: string; row_count: number; payload_bytes: number; max_cell_bytes: number}[];
  userRows.splice(userRows.findIndex((r) => r.table_name === "users"), 1);
  expect(() => collectB17PreservationSnapshot(before.plan, truncated)).toThrow("TRUNCATED");
  const oversize = clone(before.results);
  (oversize[firstId][0] as { row_count: number }).row_count = B17_PRESERVATION_LIMITS.maxTableRows + 1;
  expect(() => collectB17PreservationSnapshot(before.plan, oversize)).toThrow("LIMIT");
  const oversizedCell = clone(before.results);
  (oversizedCell[firstId][0] as { max_cell_bytes: number }).max_cell_bytes = B17_PRESERVATION_LIMITS.maxCellBytes + 1;
  expect(() => collectB17PreservationSnapshot(before.plan, oversizedCell)).toThrow("LIMIT");
  const duplicate = clone(before.results);
  duplicate[populatedId].push(clone(duplicate[populatedId].find((r) => (r as {table_name: string}).table_name === "users")!));
  expect(() => collectB17PreservationSnapshot(before.plan, duplicate)).toThrow("ROW");
  expect(() => collectB17PreservationSnapshot({ ...before.plan, complete: true }, before.results)).toThrow("PLAN");
  const omitted = clone(after.snapshot); delete omitted.tables.student_seats;
  expect(() => compareB17PreservationSnapshots(before.snapshot, omitted)).toThrow("SNAPSHOT");
  const changed = clone(after.snapshot), changedUser = changed.tables.users.rows.find((r: {rowid: string}) => r.rowid === "-91")!;
  changedUser.values[changed.tables.users.columns.indexOf("display_name")] = ["text", "RAW_VALUE_MUST_NOT_LEAK"];
  const mismatch = compareB17PreservationSnapshots(before.snapshot, changed);
  expect(mismatch.mismatchCount).toBe(1);
  expect(mismatch.mismatches).toEqual([{ table: "users", rowid: "-91", column: "display_name" }]);
  expect(JSON.stringify(mismatch)).not.toContain("RAW_VALUE_MUST_NOT_LEAK");
  const reordered = clone(after.snapshot);
  reordered.tables.users.rows.reverse();
  expect(compareB17PreservationSnapshots(before.snapshot, reordered).ok).toBe(true);
  await db.prepare("UPDATE users SET display_name=? WHERE id='b17-preserve-owner'").bind("x".repeat(B17_PRESERVATION_LIMITS.maxCellBytes + 1)).run();
  await expect(capture("after")).rejects.toThrow("LIMIT");
});
