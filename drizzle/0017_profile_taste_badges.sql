CREATE TABLE taste_badges (
  id TEXT PRIMARY KEY NOT NULL,
  category TEXT NOT NULL CHECK(category IN ('FOOD', 'TASTE', 'STYLE')),
  label TEXT NOT NULL UNIQUE,
  headline_noun TEXT NOT NULL,
  sort_order INTEGER NOT NULL DEFAULT 0,
  is_active INTEGER NOT NULL DEFAULT 1 CHECK(is_active IN (0, 1)),
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL
);

CREATE INDEX taste_badges_category_active_idx
  ON taste_badges(category, is_active, sort_order);

CREATE TABLE user_taste_badges (
  user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  badge_id TEXT NOT NULL REFERENCES taste_badges(id) ON DELETE RESTRICT,
  source TEXT NOT NULL CHECK(source IN ('USER', 'NAVER', 'GOOGLE', 'INFERRED')),
  score REAL NOT NULL CHECK(score >= 0.0 AND score <= 1.0),
  evidence_json TEXT NOT NULL DEFAULT '{}',
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL,
  PRIMARY KEY(user_id, badge_id, source)
);

CREATE INDEX user_taste_badges_user_score_idx
  ON user_taste_badges(user_id, score);
CREATE INDEX user_taste_badges_badge_idx
  ON user_taste_badges(badge_id);

